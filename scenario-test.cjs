const assert=require('node:assert/strict');
const fs=require('node:fs');
const {parseWorld}=require('./world-extended.js');
const QuestEngine=require('./engine-extended.js');
const world=parseWorld(fs.readFileSync(`${__dirname}/world.txt`,'utf8'));
assert.equal(world.locations.length,10);assert.equal(world.characters.length,1);
assert.equal(world.relations.length,7);assert.equal(world.events.length,11);assert.equal(world.endings.length,4);
assert.deepEqual(world.byName.get('Чердак').position,{x:2,y:1,z:1});
assert.deepEqual(world.byName.get('Подвал').position,{x:2,y:1,z:-1});
assert.equal(world.byName.get('Читальный зал').objects.get('старое кресло').действие,'Свернуться в кресле и дождаться утра');
assert.equal(world.byName.get('Читальный зал').items.get('открытка').эффект,'записка_прочитана');
assert.equal(world.characters[0].conditionalDialogues.length,2);
const engine=new QuestEngine(world,()=>0.9);
assert.equal(engine.exit('Читальный зал','запад',new Set()),null);
assert.equal(engine.exit('Архив','восток',new Set()),null);
assert.equal(engine.exit('Лестница','вниз',new Set()),null);
engine.effect('том_возвращён. Переход открыт.');assert.ok(engine.exit('Читальный зал','запад',new Set()));
engine.completed.set('door',{location:'Архив',link:world.relations.find(x=>x.object==='дверь кабинета')});
assert.ok(engine.exit('Архив','восток',new Set()));
engine.effect('фонарик_получен.');assert.ok(engine.exit('Лестница','вниз',new Set()));
assert.equal(engine.canFinish('Спуститься по верёвке'),true);
assert.equal(engine.canFinish('Свернуться в кресле и дождаться утра'),true);
assert.equal(engine.check('не фонарик_получен и не свет_включён','Лестница'),false);
engine.reset();assert.equal(engine.completed.size,0);assert.equal(engine.flag('том_возвращён'),0);assert.equal(engine.turn,0);
const visits=new Set(['Читальный зал']);
for(let i=0;i<3;i++)engine.tick('Читальный зал',true,visits);
assert.equal(engine.turn,3);assert.equal(engine.lastEvent,null);
engine.tick('Читальный зал',true,visits);assert.ok(engine.lastEvent);
const arrival=new QuestEngine(world,()=>0.4);arrival.nextEvent=1;arrival.tick('Лестница',true,new Set(['Лестница']));
assert.equal(arrival.lastEvent.name,'Кот оставил предмет');
assert.equal(arrival.flag('фонарик_получен'),1);
assert.equal(engine.characters[0].location,'Читальный зал');
const moving=new QuestEngine(world,()=>0);moving.tick(world.start);moving.tick(world.start);moving.tick(world.start);
assert.equal(moving.characters[0].location,'Архив');
const resumed=new QuestEngine(world,()=>0.9);resumed.restoreState(moving.exportState());
assert.equal(resumed.characters[0].location,'Архив');
assert.equal(resumed.characters[0].ticks,moving.characters[0].ticks);
const cycle=parseWorld('ЛОКАЦИЯ\nНачало\nПЕРЕХОДЫ\nвосток -> Дальше\nЛОКАЦИЯ\nДальше\nПЕРЕХОДЫ\nзапад -> Начало');assert.equal(cycle.locations.length,2);
assert.throws(()=>parseWorld('ЛОКАЦИЯ\nНачало\nПЕРЕХОДЫ\nсевер -> Нет'),/неизвестную/);
